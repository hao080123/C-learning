/*A 题 · 积分最高的一天（基础，10～15 分钟）

给定 n 天的训练积分，找出积分最高的一天。若多天并列最高，选择日期最早的一天。日期从 1 开始编号。

输入格式　第一行输入 n。第二行输入 n 个整数，依次表示每天的积分。
输出格式　输出一行，依次为最高积分和对应日期，用空格分隔。
数据范围　1 ≤ n ≤ 1000，每天的积分在 -1000～1000 之间。

样例输入
5
-8 -3 -6 -3 -9

样例输出
-3 2

提示　读到第一天时，同时记下它的积分和日期。之后遇到同分时，保留已有日期。
*/
#include<iostream>
using namespace std;
int main()
{
	int n;
	cin>>n;
	int a[1001];
	for(int i=1;i<=n;i++) 
	cin>>a[i];
	int max=a[1];
	int rev=1;
	for(int i=2;i<=n;i++)
	{
		if(a[i]>max)
		{
			max=a[i];
			rev=i;
		}
	}	cout<<max<<" "<<rev;
	return 0;
}



/*B 题 · 有限预算买文具（基础，15～20 分钟）

商店有 n 件文具，每件都有一个价格，每件最多买一次。你有 m 元，求最多能买多少件。若有多种买法能买到同样多的件数，输出其中最少的花费。预算恰好用完也可以。

输入格式　第一行输入 n 和 m。第二行输入 n 个整数，依次表示每件文具的价格。
输出格式　输出一行，依次为最多购买件数和对应的最少花费，用空格分隔。
数据范围　1 ≤ n ≤ 1000，`0 ≤ m ≤ 1000000`，每件文具的价格在 1～1000 元之间。

样例输入
6 12
8 4 3 6 2 3

样例输出
4 12

提示　把价格从小到大排。先想想，如果要买恰好 k 件，怎样选才能花费最少。价格相同的文具可以分别购买。
*/
#include<iostream>
using namespace std;
int main()
{
	int n,m;
	cin>>n>>m;
	int num=0;
	int a[1000];
	for(int i=0;i<n;i++)
	cin>>a[i];
	for(int i=1;i<n;i++)
	{
		for(int d=1;d<=n-i;d++)
		{
			if(a[d]<a[d-1])
			{
				int t=a[d];
				a[d]=a[d-1];
				a[d-1]=t;
			}
		}
	}
	int budget=m;
	for(int i=0;i<n;i++)
	{
	 if(m<a[i]) break;
	 m-=a[i];num++;
	}
	cout<<num<<" "<<budget-m;
	return 0;	
}


/*C 题 · 矩形区域积分（可选提高，20～25 分钟）

一张积分表有 n 行、`m` 列，行号和列号都从 1 开始。每次给出矩形的左上角和右下角，求矩形内所有格子的积分之和，包含边界。矩形可以只有一行、一列或一个格子。

输入格式　第一行输入 n、`m`、`q`，其中 q 是查询次数。接下来 n 行，每行输入 m 个整数，表示这一行的积分。再输入 q 行，每行四个整数 r1 c1 r2 c2，表示左上角和右下角的行列编号。
输出格式　每次查询输出一行，表示矩形的积分之和。
数据范围　1 ≤ n, m ≤ 100，`1 ≤ q ≤ 10000`，每格积分在 -1000～1000 之间。每次查询满足 1 ≤ r1 ≤ r2 ≤ n、`1 ≤ c1 ≤ c2 ≤ m`。

样例输入
3 4 3
2 -1 3 0
4 5 -2 1
-3 2 6 -4
1 2 2 3
1 1 3 4
3 4 3 4

样例输出
5
13
-4

提示　把一个矩形拆成几行。每一行都只查询第 c1 列到第 c2 列，可以对每一行分别建立你已经练过的一维前缀和，再把各行的结果加起来。
*/
#include<iostream>
using namespace std;
int main()
{
	int n,m,q;cin>>n>>m>>q;
	int r1,c1,r2,c2;
	int pre[101][101]={0};
	int a[101][101];
	for(int i=1;i<=n;i++)
	{
	for(int j=1;j<=m;j++)
	{
	cin>>a[i][j];
	pre[i][j]=pre[i][j-1]+a[i][j];
	}}
	for(int i=0;i<q;i++)
	{
	 cin>>r1>>c1>>r2>>c2;
	 int sum=0; 
	for(int i=r1;i<=r2;i++)
	{
	  sum+=pre[i][c2]-pre[i][c1-1];
	}
      cout<<sum<<endl;
}
}























































