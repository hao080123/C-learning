/*第 1 题｜最接近的两个数（基础，12～15 分钟）

给定 n 个整数，从不同位置选出两个数，使它们的差的绝对值最小。如果有多组并列，选择其中较小的那个数最小的一组。两个位置上的数值可以相同。

输入格式　第一行输入 n，第二行输入 n 个整数。
输出格式　第一行输出最小差值。第二行输出选出的两个数，按从小到大排列，用空格分隔。
数据范围　2 ≤ n ≤ 1000，每个数在 -1000～1000 之间。

样例输入
4
4 0 -2 2

样例输出
2
-2 0

提示　排序后比较相邻的数。用第一对的差值和两个下标初始化答案，再比较剩下的数对。补测 n = 2，确保只有一对时也能输出正确的两个数。
*/
#include<iostream>
using namespace std;
int main()
{
	int n;cin>>n;
	int a[1002];
	for(int i=0;i<n;i++)
	cin>>a[i];
	for(int i=1;i<n;i++)
	{
		for(int d=1;d<=n-i;d++)
		{
			if(a[d]<a[d-1])
			{
				int t=a[d];
				a[d]=a[d-1];
				a[d-1]=t;
			}
		}
	}
    int min=0;
    int v,r;
	for(int i=1;i<n;i++)
	{
		if(min<a[i]-a[i-1])
		{
			min=a[i]-a[i-1];
			r=a[i];
			v=a[i-1];
		}
	}
	cout<<min<<endl<<v<<" "<<r;
	return 0;
}



